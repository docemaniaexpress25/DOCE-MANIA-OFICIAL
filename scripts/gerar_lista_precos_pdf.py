# L tier: surfaces (area 20-50%, S <= 0.15)
CARD_BG       = colors.HexColor('#e6e9e7')
TABLE_STRIPE  = colors.HexColor('#edf0ef')

# M tier: structural fills (area 5-20%, S <= 0.30)
HEADER_FILL   = colors.HexColor('#466556')
COVER_BLOCK   = colors.HexColor('#3d5d4d')

# S tier: edges & icons (area 1-5%, S <= 0.50)
BORDER        = colors.HexColor('#b8c6bf')
ICON          = colors.HexColor('#539172')

# XS tier: emphasis (area < 1%, S <= 0.75)
ACCENT        = colors.HexColor('#209159')
ACCENT_2      = colors.HexColor('#55a9c5')

# Typography
TEXT_PRIMARY  = colors.HexColor('#1d201e')
TEXT_MUTED    = colors.HexColor('#7d8782')

# Table colors (derived from cascade tiers — NOT from ACCENT)
TABLE_HEADER_COLOR = HEADER_FILL      # M tier, low-sat — harmonious with body
TABLE_HEADER_TEXT  = colors.white     # White text on dark header
TABLE_ROW_EVEN     = colors.white     # Clean white
TABLE_ROW_ODD      = TABLE_STRIPE     # L tier, very subtle stripe

# ─────────────────────────────────────────────────────────────────────────────
# PAGINA / MARGENS
# ─────────────────────────────────────────────────────────────────────────────
PAGE_W, PAGE_H = A4                    # 595.28 x 841.89 pt
MARGIN_L = 46
MARGIN_R = 46
MARGIN_T = 40
MARGIN_B = 56                          # espaco para o rodape
AVAIL_W = PAGE_W - MARGIN_L - MARGIN_R  # ~503 pt

# ─────────────────────────────────────────────────────────────────────────────
# ESTILOS
# ─────────────────────────────────────────────────────────────────────────────
ST_MARCA = ParagraphStyle(
    "Marca", fontName="LibSans-Bold", fontSize=24, leading=26,
    textColor=colors.white, alignment=TA_LEFT,
)
ST_SUBTITULO = ParagraphStyle(
    "Subtitulo", fontName="LibSans", fontSize=12.5, leading=16,
    textColor=colors.HexColor('#d7e4dc'), alignment=TA_LEFT,
)
ST_META_CLARO = ParagraphStyle(
    "MetaClaro", fontName="LibSans", fontSize=9, leading=12,
    textColor=colors.HexColor('#cfdeda'), alignment=TA_RIGHT,
)
ST_STAT_NUM = ParagraphStyle(
    "StatNum", fontName="LibSans-Bold", fontSize=15, leading=18,
    textColor=HEADER_FILL, alignment=TA_CENTER,
)
ST_STAT_LBL = ParagraphStyle(
    "StatLbl", fontName="LibSans", fontSize=7.6, leading=10,
    textColor=TEXT_MUTED, alignment=TA_CENTER,
)
ST_TH = ParagraphStyle(
    "TH", fontName="LibSans-Bold", fontSize=9.5, leading=12,
    textColor=TABLE_HEADER_TEXT, alignment=TA_LEFT,
)
ST_TH_RIGHT = ParagraphStyle(
    "THRight", parent=ST_TH, alignment=TA_RIGHT,
)
ST_TD = ParagraphStyle(
    "TD", fontName="LibSans", fontSize=9.5, leading=12.5,
    textColor=TEXT_PRIMARY, alignment=TA_LEFT,
)
ST_TD_NUM = ParagraphStyle(
    "TDNum", parent=ST_TD, alignment=TA_CENTER, textColor=TEXT_MUTED,
    fontSize=8.5,
)
ST_TD_PRECO = ParagraphStyle(
    "TDPreco", parent=ST_TD, fontName="LibSans-Bold", alignment=TA_RIGHT,
)
ST_LETRA = ParagraphStyle(
    "Letra", fontName="LibSans-Bold", fontSize=10, leading=13,
    textColor=COVER_BLOCK, alignment=TA_LEFT,
)
ST_NOTA_TIT = ParagraphStyle(
    "NotaTit", fontName="LibSans-Bold", fontSize=9, leading=12,
    textColor=HEADER_FILL, alignment=TA_LEFT,
)
ST_NOTA = ParagraphStyle(
    "Nota", fontName="LibSans", fontSize=8.2, leading=11.5,
    textColor=TEXT_MUTED, alignment=TA_LEFT,
)

# ─────────────────────────────────────────────────────────────────────────────
# RODAPE COM "Página X de Y" (padrao NumberedCanvas)
# ─────────────────────────────────────────────────────────────────────────────
class NumeredCanvas(canvas_module.Canvas):
    """BLOCO 229 (R4): numeracao total apos o build (duas passadas)."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._desenhar_rodape(total)
            super().showPage()
        super().save()

    def _desenhar_rodape(self, total: int):
        self.saveState()
        # linha superior do rodape
        self.setStrokeColor(BORDER)
        self.setLineWidth(0.6)
        y_line = MARGIN_B - 14
        self.line(MARGIN_L, y_line, PAGE_W - MARGIN_R, y_line)
        # textos
        self.setFont("LibSans", 7.5)
        self.setFillColor(TEXT_MUTED)
        self.drawString(
            MARGIN_L, y_line - 12,
            "DOCE MANIA  •  Lista de Preços de Venda  •  Uso interno",
        )
        self.drawRightString(
            PAGE_W - MARGIN_R, y_line - 12,
            f"Página {self._pageNumber} de {total}",
        )
        self.restoreState()


# ─────────────────────────────────────────────────────────────────────────────
# UTILITARIOS
# ─────────────────────────────────────────────────────────────────────────────
def fmt_brl(valor: float) -> str:
    """R$ 1.234,56 — formato brasileiro."""
    s = f"{valor:,.2f}"
    return "R$ " + s.replace(",", "X").replace(".", ",").replace("X", ".")


def esc(texto: str) -> str:
    return html.escape(str(texto), quote=False)


# ─────────────────────────────────────────────────────────────────────────────
# MONTAGEM DO DOCUMENTO
# ─────────────────────────────────────────────────────────────────────────────
def gerar() -> str:
    raiz = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    origem = "/tmp/produtos_finais.json"
    destino = os.path.join(raiz, "public", "DOCE-MANIA-Lista-De-Precos.pdf")

    with open(origem, "r", encoding="utf-8") as f:
        produtos = json.load(f)

    produtos.sort(key=lambda p: p["nome"].strip().lower())
    agora = datetime.now(ZoneInfo("America/Sao_Paulo"))
    data_geracao = agora.strftime("%d/%m/%Y às %H:%M")

    doc = SimpleDocTemplate(
        destino, pagesize=A4,
        leftMargin=MARGIN_L, rightMargin=MARGIN_R,
        topMargin=MARGIN_T, bottomMargin=MARGIN_B,
        title="DOCE MANIA — Lista de Preços de Venda",
        author="DOCE MANIA",
        subject="Lista de preços de venda dos produtos ativos",
        creator="DOCE MANIA",
    )

    story = []

    # ── Faixa de cabecalho (M tier — HEADER_FILL) ──
    meta_direita = Paragraph(
        f"Gerada em {data_geracao}<br/>Valores em reais (R$)",
        ST_META_CLARO,
    )
    marca = [Paragraph("DOCE MANIA", ST_MARCA),
             Paragraph("LISTA DE PREÇOS DE VENDA", ST_SUBTITULO)]
    faixa = Table(
        [[marca, meta_direita]],
        colWidths=[AVAIL_W * 0.62, AVAIL_W * 0.38],
    )
    faixa.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), HEADER_FILL),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (0, 0), 18),
        ("RIGHTPADDING", (1, 0), (1, 0), 18),
        ("TOPPADDING", (0, 0), (-1, -1), 14),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 14),
        ("LINEBELOW", (0, 0), (-1, -1), 3, ACCENT),
    ]))
    story.append(faixa)
    story.append(Spacer(1, 12))

    # ── Resumo em 3 cartoes (L tier — CARD_BG) ──
    precos = [float(p["preco_venda"]) for p in produtos]
    stats = [
        (str(len(produtos)), "PRODUTOS ATIVOS"),
        (fmt_brl(min(precos)), "MENOR PREÇO"),
        (fmt_brl(max(precos)), "MAIOR PREÇO"),
    ]
    linha_stats = [[
        [Paragraph(num, ST_STAT_NUM), Paragraph(lbl, ST_STAT_LBL)]
        for num, lbl in stats
    ]]
    cartoes = Table(linha_stats, colWidths=[AVAIL_W / 3.0] * 3)
    cartoes.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEAFTER", (0, 0), (1, -1), 0.8, BORDER),
    ]))
    story.append(cartoes)
    story.append(Spacer(1, 14))

    # ── Tabela principal: # | Produto | Preço de Venda ──
    w_num = 32.0
    w_preco = 96.0
    w_nome = AVAIL_W - w_num - w_preco   # soma = AVAIL_W (regra do brief)

    dados = [[
        Paragraph("#", ST_TH),
        Paragraph("NOME DO PRODUTO", ST_TH),
        Paragraph("PREÇO DE VENDA", ST_TH_RIGHT),
    ]]

    estilos_extra = []
    linha_dados = 1          # linha corrente na tabela (0 = cabecalho)
    zebra = 0                # alterna listrado/branco SOMENTE em linhas de produto
    letra_atual = None

    for idx, p in enumerate(produtos, start=1):
        nome = str(p["nome"]).strip()
        inicial = nome[0].upper()

        if inicial != letra_atual:
            # divisor de letra — ocupa as 3 colunas (span)
            dados.append([Paragraph(inicial, ST_LETRA), "", ""])
            estilos_extra.append(("SPAN", (0, linha_dados), (-1, linha_dados)))
            estilos_extra.append(("BACKGROUND", (0, linha_dados), (-1, linha_dados), SECTION_BG))
            estilos_extra.append(("TOPPADDING", (0, linha_dados), (-1, linha_dados), 4))
            estilos_extra.append(("BOTTOMPADDING", (0, linha_dados), (-1, linha_dados), 4))
            estilos_extra.append(("LEFTPADDING", (0, linha_dados), (-1, linha_dados), 8))
            letra_atual = inicial
            linha_dados += 1
            zebra = 0

        dados.append([
            Paragraph(str(idx), ST_TD_NUM),
            Paragraph(esc(nome), ST_TD),
            Paragraph(fmt_brl(float(p["preco_venda"])), ST_TD_PRECO),
        ])
        estilos_extra.append((
            "BACKGROUND", (0, linha_dados), (-1, linha_dados),
            TABLE_ROW_ODD if zebra % 2 == 1 else TABLE_ROW_EVEN,
        ))
        zebra += 1
        linha_dados += 1

    tabela = Table(
        dados,
        colWidths=[w_num, w_nome, w_preco],
        repeatRows=1,   # BLOCO 229 (R4): cabecalho repete em toda pagina
    )
    tabela.setStyle(TableStyle([
        # cabecalho
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("LINEBELOW", (0, 0), (-1, 0), 1.2, COVER_BLOCK),
        ("TOPPADDING", (0, 0), (-1, 0), 7),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 7),
        # corpo
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 1), (-1, -1), 4.5),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 4.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        # linhas horizontais discretas
        ("LINEBELOW", (0, 1), (-1, -1), 0.4, BORDER),
        # coluna de preco destacada
        ("LINEBEFORE", (2, 0), (2, -1), 0.8, BORDER),
    ] + estilos_extra))
    story.append(tabela)

    # ── Nota final ──
    story.append(Spacer(1, 16))
    story.append(Paragraph("COMO ESTA LISTA FOI MONTADA", ST_NOTA_TIT))
    story.append(Spacer(1, 3))
    story.append(Paragraph(
        "Contém os <b>133 produtos ATIVOS</b> do catálogo, em ordem alfabética. "
        "Foram excluídos <b>7 produtos de teste</b> e <b>2 produtos fora de linha</b> "
        "(Batata Wanflo lisa e Batata Wanflo ondulada, desativados no sistema). "
        "Os preços são os cadastrados no campo PREÇO DE VENDA em "
        f"{data_geracao} e podem ser atualizados a qualquer momento pelo painel de produtos.",
        ST_NOTA,
    ))

    doc.build(story, canvasmaker=NumeredCanvas)
    return destino


if __name__ == "__main__":
    caminho = gerar()
    tamanho_kb = os.path.getsize(caminho) / 1024.0
    print(f"OK: {caminho} ({tamanho_kb:.1f} KB)")
