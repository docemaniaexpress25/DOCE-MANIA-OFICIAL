"""
BLOCO 229 — GERADOR DA LISTA DE PRECOS DE VENDA EM PDF (regra do dono).
Gera `public/DOCE-MANIA-Lista-De-Precos.pdf` a partir de /tmp/produtos_finais.json
(produtos ATIVOS, SEM os de teste e SEM os fora de linha — filtro feito antes).

Regras aplicadas:
  R1. Somente colunas pedidas: NOME DO PRODUTO + PRECO DE VENDA (facil entendimento).
  R2. Sem produtos de teste (flag produto_teste OU nome contendo "teste").
  R3. Paleta obrigatoria via palette.cascade (verde Doce Mania, baixa saturacao).
  R4. Cabecalho repetido em toda pagina (repeatRows=1) + rodape com Página X de Y.
  R5. Divisores por letra inicial (A, B, C...) para facilitar a consulta.

Uso: python3 scripts/gerar_lista_precos_pdf.py
"""
import json
import os
import html
from datetime import datetime

from zoneinfo import ZoneInfo

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.enums import TA_LEFT, TA_RIGHT, TA_CENTER
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas as canvas_module
